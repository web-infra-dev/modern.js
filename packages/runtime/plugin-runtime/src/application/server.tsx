import { PassThrough, Readable } from 'node:stream';
import type { RequestHandlerOptions } from '@modern-js/app-tools';
import React from 'react';
import { renderToPipeableStream } from 'react-dom/server';
import { getCurrentEntryName } from '../core/context';
import { wrapRuntimeContextProvider } from '../core/react/wrapper';
import { createRequestHandler } from '../core/server/requestHandler';
import { serializeErrors } from '../router/runtime/utils';
import type { ApplicationSnapshot } from './types';

export type { ApplicationSnapshot } from './types';

export interface RenderApplicationOptions {
  identifierPrefix: string;
  basename?: string;
  props?: Record<string, unknown>;
  nonce?: string;
  signal?: AbortSignal;
  loaderContext?: Map<string, unknown>;
  onError?: (error: unknown) => void;
}

export interface ApplicationStream {
  stream: ReadableStream<Uint8Array>;
  snapshot: Promise<ApplicationSnapshot>;
  cancel: (reason?: unknown) => void;
}

/** Resolve deferred loader values before transporting the hydration snapshot. */
async function resolveData(value: unknown): Promise<unknown> {
  const resolved = await value;
  if (Array.isArray(resolved)) {
    return Promise.all(resolved.map(resolveData));
  }
  if (resolved && typeof resolved === 'object') {
    if (resolved instanceof Date) return resolved.toJSON();
    return Object.fromEntries(
      await Promise.all(
        Object.entries(resolved).map(async ([key, item]) => [
          key,
          await resolveData(item),
        ]),
      ),
    );
  }
  return resolved;
}

/**
 * Render the registered application using its own runtime and React renderer.
 * The registry is generated by Modern, including real routes and data loaders.
 * The caller owns framing, transport, assets, and the outer HTML document.
 */
export async function renderApplication(
  request: Request,
  options: RenderApplicationOptions,
): Promise<ApplicationStream> {
  if (!options.identifierPrefix) {
    throw new Error('renderApplication requires a unique identifierPrefix');
  }
  const signal = options.signal || request.signal;
  signal.throwIfAborted();
  const basename = options.basename || '/';
  const props = options.props || {};
  let result: ApplicationStream | undefined;

  const handler = await createRequestHandler(
    async (_request, Root, context) => {
      const { runtimeContext } = context;
      runtimeContext.ssr = true;
      const element = wrapRuntimeContextProvider(
        <Root {...props} />,
        runtimeContext,
      );
      const output = new PassThrough();
      let resolveSnapshot!: (snapshot: ApplicationSnapshot) => void;
      let rejectSnapshot!: (error: unknown) => void;
      const snapshot = new Promise<ApplicationSnapshot>((resolve, reject) => {
        resolveSnapshot = resolve;
        rejectSnapshot = reject;
      });
      // Consumers normally read the stream before awaiting the snapshot.
      void snapshot.catch(() => {});
      let abortRender: (reason?: unknown) => void = () => {};
      let failed = false;
      const fail = (reason: unknown) => {
        if (failed) return;
        failed = true;
        const error =
          reason instanceof Error ? reason : new Error(String(reason));
        rejectSnapshot(error);
        // Close transport before aborting React: abort can synchronously write
        // client-render instructions, which must not escape a cancelled task.
        output.destroy(error);
        abortRender(error);
      };
      const abort = () =>
        fail(signal.reason || new Error('Application render aborted'));
      signal.addEventListener('abort', abort, { once: true });
      output.once('close', () => {
        signal.removeEventListener('abort', abort);
        if (!output.writableFinished)
          fail(new Error('Application stream was cancelled'));
      });
      output.once('error', rejectSnapshot);
      output.once('finish', () => {
        if (failed) return;
        void (async () => {
          const router = runtimeContext.routerContext;
          const value: ApplicationSnapshot = {
            protocol: 'modern-application/1',
            reactVersion: React.version,
            identifierPrefix: options.identifierPrefix,
            url: request.url,
            basename,
            props,
            initialData: runtimeContext.initialData,
            routerData: router
              ? {
                  loaderData: router.loaderData,
                  errors: serializeErrors(router.errors),
                }
              : undefined,
          };
          // JSON round-trip both validates and removes undefined properties.
          resolveSnapshot(JSON.parse(JSON.stringify(await resolveData(value))));
        })().catch(rejectSnapshot);
      });
      const stream = Readable.toWeb(output) as ReadableStream<Uint8Array>;
      result = { stream, snapshot, cancel: fail };
      await new Promise<void>((resolve, reject) => {
        const rendered = renderToPipeableStream(element, {
          identifierPrefix: options.identifierPrefix,
          nonce: options.nonce,
          onShellReady() {
            rendered.pipe(output);
            resolve();
          },
          onShellError(error) {
            fail(error);
            reject(error);
          },
          onError(error) {
            options.onError?.(error);
            // Do not publish a successful hydration snapshot after React aborted
            // a boundary; the transport can now apply its failure policy.
            fail(error);
            reject(error);
          },
        });
        abortRender = rendered.abort;
        if (signal.aborted) {
          abort();
          reject(signal.reason);
        }
      });
      return new Response(stream);
    },
    { runtimeContext: { _application: { url: request.url, props } } },
  );
  const entryName = getCurrentEntryName() || 'index';
  const noop = () => {};
  const handlerOptions = {
    resource: {
      entryName,
      route: { entryName, urlPath: basename, isSSR: true },
      routeManifest: {},
      loadableStats: {},
      htmlTemplate: '',
    },
    config: { ssr: { mode: 'stream' }, nonce: options.nonce },
    params: {},
    loaderContext: options.loaderContext || new Map(),
    monitors: {
      error: options.onError || noop,
      warn: noop,
      info: noop,
      debug: noop,
      trace: noop,
      push: noop,
      timing: noop,
      counter: noop,
    },
    onError: options.onError || noop,
    onTiming: noop,
  } as unknown as RequestHandlerOptions;
  const response = await handler(request, handlerOptions);
  if (!result) {
    // Redirects and other short-circuit responses are not an application stream.
    throw new Error(
      `Application request returned HTTP ${response.status} before rendering`,
    );
  }
  return result;
}
