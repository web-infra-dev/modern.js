import type React from 'react';
import { Helmet } from 'react-helmet';
import {
  getGlobalInternalRuntimeContext,
  setGlobalInternalRuntimeContext,
} from '../../src/core/context';
import { renderString } from '../../src/core/server/server';

const HTML_PLACEHOLDER = '<!--<?- html ?>-->';
const CHUNK_JS_PLACEHOLDER = '<!--<?- chunksMap.js ?>-->';
const CHUNK_CSS_PLACEHOLDER = '<!--<?- chunksMap.css ?>-->';
const SSR_DATA_PLACEHOLDER = '<!--<?- SSRDataScript ?>-->';

const jsChunk = '<script defer src="/static/js/async/page.js"></script>';
const cssChunk = '<link href="/static/css/async/page.css" rel="stylesheet" />';

// The template generated by Modern.js by default, which has no `<title>`
// unless `html.title` is configured.
const defaultTemplate = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <script defer src="/static/js/main.js"></script>
</head>
<body>
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- chunksMap.js ?>-->
  <!--<?- SSRDataScript ?>-->
  <!--<?- bottomTemplate ?>-->
</body>
</html>`;

const titleTemplate = `<!DOCTYPE html>
<html lang="zh">
<head>
  <meta charset="utf-8">
  <title>Default Title</title>
  <!--<?- chunksMap.css ?>-->
</head>
<body class="light">
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- chunksMap.js ?>-->
  <!--<?- SSRDataScript ?>-->
</body>
</html>`;

const headChunksTemplate = `<!DOCTYPE html>
<html>
<head>
  <title></title>
  <!--<?- chunksMap.css ?>-->
  <!--<?- chunksMap.js ?>-->
</head>
<body>
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- SSRDataScript ?>-->
</body>
</html>`;

// The only <title> of the template is in a footer after the app html.
const footerTitleTemplate = `<!DOCTYPE html>
<html>
<head>
  <!--<?- chunksMap.css ?>-->
</head>
<body>
  <div id="root"><!--<?- html ?>--></div>
  <footer><svg><title>Logo</title></svg></footer>
  <!--<?- chunksMap.js ?>-->
  <!--<?- SSRDataScript ?>-->
</body>
</html>`;

const templates = {
  defaultTemplate,
  titleTemplate,
  headChunksTemplate,
  footerTitleTemplate,
};

const Content = () => (
  <main>
    <h1 className="title">Hello Modern.js</h1>
    <svg viewBox="0 0 10 10" aria-hidden="true">
      <path d="M0 0L10 10" />
    </svg>
    <ul>
      {['a', 'b', 'c'].map(item => (
        <li key={item}>{`Item ${item}`}</li>
      ))}
    </ul>
  </main>
);

const apps: Record<string, () => React.ReactElement> = {
  withoutHelmet: () => <Content />,
  helmetTitle: () => (
    <>
      <Helmet>
        <title>Page Title</title>
        <meta name="description" content="page description" />
      </Helmet>
      <Content />
    </>
  ),
  helmetAttributes: () => (
    <>
      <Helmet
        htmlAttributes={{ lang: 'en' }}
        bodyAttributes={{ class: 'dark' }}
      >
        <title>Page Title</title>
        <link rel="canonical" href="https://modernjs.dev/" />
        <style>{'body { margin: 0; }'}</style>
        <script>{'window.__helmet = true;'}</script>
      </Helmet>
      <Content />
    </>
  ),
  // the app html contains a <title>, e.g. of an svg icon or a React 19 <title>
  svgTitle: () => (
    <>
      <Content />
      <svg>
        <title>Close</title>
      </svg>
    </>
  ),
  svgTitleWithHelmet: () => (
    <>
      <Helmet>
        <title>Page Title</title>
      </Helmet>
      <Content />
      <svg>
        <title>Close</title>
      </svg>
    </>
  ),
  // Helmet inlines scripts as is, so they can contain placeholder-like text.
  helmetScriptWithPlaceholders: () => (
    <>
      <Helmet>
        <script>{`window.__html = "${HTML_PLACEHOLDER}${SSR_DATA_PLACEHOLDER}";`}</script>
      </Helmet>
      <Content />
    </>
  ),
  reactTitle: () => (
    <>
      <title>React Title</title>
      <Content />
    </>
  ),
};

function createRenderOptions(
  htmlTemplate: string,
  htmlModifiers: ((html: string) => string | Promise<string>)[] = [],
) {
  const ssrContext = {
    request: {
      params: {},
      query: {},
      pathname: '/',
      host: 'localhost:8080',
      url: 'http://localhost:8080/',
      headers: {},
    },
    reporter: { sessionId: 'session-id' },
    htmlModifiers,
  };
  return {
    resource: {
      htmlTemplate,
      entryName: 'main',
      route: {},
      loadableStats: undefined,
      routeManifest: undefined,
    },
    runtimeContext: { ssrContext },
    config: { ssr: { mode: 'string' } },
    onError: rstest.fn(),
    onTiming: rstest.fn(),
  } as any;
}

function render(htmlTemplate: string, app: React.ReactElement) {
  return renderString(
    new Request('http://localhost:8080/'),
    app,
    createRenderOptions(htmlTemplate),
  );
}

describe('renderString html building', () => {
  const previousContext = getGlobalInternalRuntimeContext();

  afterAll(() => {
    setGlobalInternalRuntimeContext(previousContext);
  });

  beforeAll(() => {
    setGlobalInternalRuntimeContext({
      hooks: {
        extendStringSSRCollectors: {
          call: ({
            chunkSet,
          }: {
            chunkSet: { jsChunk: string; cssChunk: string };
          }) => [
            {
              effect() {
                chunkSet.jsChunk += jsChunk;
                chunkSet.cssChunk += cssChunk;
              },
            },
          ],
        },
      },
    } as any);
  });

  const cases = Object.keys(templates).flatMap(template =>
    Object.keys(apps).map(app => [template, app]),
  ) as [keyof typeof templates, keyof typeof apps][];

  it.each(cases)(
    'should render complete HTML for %s and %s',
    async (templateName, appName) => {
      const template = templates[templateName];
      const App = apps[appName];

      const html = await render(template, <App />);

      expect(html).toMatch(/^<!DOCTYPE html>\s*<html/);
      expect(html).toMatch(/<\/body>\s*<\/html>$/);
      if (template.includes(CHUNK_CSS_PLACEHOLDER)) {
        expect(html).toContain(cssChunk);
      }
      expect(html).toContain('<h1 class="title">Hello Modern.js</h1>');
      expect(html).toContain(jsChunk);
      expect(html).toContain('window._SSR_DATA');
      // Every template placeholder is replaced, the Helmet script keeps its text.
      const outsideHelmetScript = html.replace(/window\.__html = "[^"]*";/, '');
      expect(outsideHelmetScript).not.toContain(HTML_PLACEHOLDER);
      expect(outsideHelmetScript).not.toContain(CHUNK_JS_PLACEHOLDER);
      expect(outsideHelmetScript).not.toContain(SSR_DATA_PLACEHOLDER);
      expect(outsideHelmetScript).not.toContain(CHUNK_CSS_PLACEHOLDER);

      if (appName === 'svgTitle') {
        expect(html).toContain('<svg><title>Close</title></svg>');
      }
      if (appName === 'svgTitleWithHelmet') {
        const expectedTitle =
          templateName === 'titleTemplate' ||
          templateName === 'headChunksTemplate'
            ? '<title>Close</title>'
            : '<title data-react-helmet="true">Page Title</title>';
        expect(html).toContain(`<svg>${expectedTitle}</svg>`);
        expect(html.match(/<title[^>]*>Page Title<\/title>/g)).toHaveLength(1);
      }
      if (appName === 'reactTitle') {
        expect(html).toContain('<title>React Title</title><main>');
      }
      if (appName === 'helmetScriptWithPlaceholders') {
        expect(html).toContain(
          `window.__html = "${HTML_PLACEHOLDER}${SSR_DATA_PLACEHOLDER}";`,
        );
      }
      if (appName === 'helmetTitle' || appName === 'helmetAttributes') {
        expect(html).toContain(
          '<title data-react-helmet="true">Page Title</title>',
        );
        expect(html).not.toContain('<title>Default Title</title>');
      }
      if (appName === 'helmetTitle') {
        expect(html).toContain(
          '<meta data-react-helmet="true" name="description" content="page description"/>',
        );
      }
      if (appName === 'helmetAttributes') {
        expect(html).toContain('<html lang="en">');
        expect(html).toContain('<body class="dark">');
        expect(html).toContain(
          '<link data-react-helmet="true" rel="canonical" href="https://modernjs.dev/"/>',
        );
        expect(html).toContain('body { margin: 0; }');
        expect(html).toContain('window.__helmet = true;');
      }
    },
  );

  it('should not add the helmet title when the app html has a title', async () => {
    const html = await render(defaultTemplate, <apps.reactTitle />);

    expect(html).toContain('<div id="root"><title>React Title</title><main>');
    expect(html).not.toContain('<title data-react-helmet="true">');
  });

  it('should only replace the placeholders of the template', async () => {
    const appHtml = [
      HTML_PLACEHOLDER,
      CHUNK_JS_PLACEHOLDER,
      CHUNK_CSS_PLACEHOLDER,
      SSR_DATA_PLACEHOLDER,
    ].join('');
    const html = await render(
      defaultTemplate,
      <div dangerouslySetInnerHTML={{ __html: appHtml }} />,
    );

    expect(html).toContain(`<div id="root"><div>${appHtml}</div></div>`);
    expect(html).toContain(`</div></div>\n  ${jsChunk}\n  <script>`);
  });

  it('should preserve app titles and literal placeholders with a template title', async () => {
    const appHtml = `<svg><title>Close</title></svg>${CHUNK_JS_PLACEHOLDER}`;
    const html = await render(
      titleTemplate,
      <div dangerouslySetInnerHTML={{ __html: appHtml }} />,
    );

    expect(html).toContain(`<div id="root"><div>${appHtml}</div></div>`);
    expect(html).toContain(`</div></div>\n  ${jsChunk}\n  <script>`);
  });

  it('should run html modifiers on the complete html', async () => {
    const htmlModifier = rstest.fn(
      (template: string) => `${template}<!-- modified -->`,
    );
    const html = await renderString(
      new Request('http://localhost:8080/'),
      <Content />,
      createRenderOptions(titleTemplate, [htmlModifier]),
    );

    expect(htmlModifier).toHaveBeenCalledTimes(1);
    const [document] = htmlModifier.mock.calls[0];
    expect(document).toContain('<h1 class="title">Hello Modern.js</h1>');
    expect(document).toContain('window._SSR_DATA');
    expect(document).toContain(jsChunk);
    expect(document).toContain(cssChunk);
    expect(html).toBe(`${document}<!-- modified -->`);
  });
});
