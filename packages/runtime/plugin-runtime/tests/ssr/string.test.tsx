import { SSR_HYDRATION_ID_PREFIX } from '@modern-js/utils/universal/constants';
import type React from 'react';
import ReactDomServer from 'react-dom/server';
import { Helmet } from 'react-helmet';
import { RenderLevel } from '../../src/core/constants';
import {
  getGlobalInternalRuntimeContext,
  setGlobalInternalRuntimeContext,
} from '../../src/core/context';
import {
  CHUNK_CSS_PLACEHOLDER,
  CHUNK_JS_PLACEHOLDER,
  HTML_PLACEHOLDER,
  SSR_DATA_PLACEHOLDER,
} from '../../src/core/server/constants';
import { createReplaceHelemt } from '../../src/core/server/helmet';
import { type BuildHtmlCb, buildHtml } from '../../src/core/server/shared';
import { renderString } from '../../src/core/server/string';
import { SSRDataCollector } from '../../src/core/server/string/ssrData';
import type { ChunkSet } from '../../src/core/server/string/types';
import { safeReplace } from '../../src/core/server/utils';

const jsChunk = '<script defer src="/static/js/async/page.js"></script>';
const cssChunk = '<link href="/static/css/async/page.css" rel="stylesheet" />';

// The template generated by Modern.js by default, which has no `<title>`
// unless `html.title` is configured.
const defaultTemplate = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <script defer src="/static/js/main.js"></script>
</head>
<body>
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- chunksMap.js ?>-->
  <!--<?- SSRDataScript ?>-->
  <!--<?- bottomTemplate ?>-->
</body>
</html>`;

const titleTemplate = `<!DOCTYPE html>
<html lang="zh">
<head>
  <meta charset="utf-8">
  <title>Default Title</title>
  <!--<?- chunksMap.css ?>-->
</head>
<body class="light">
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- chunksMap.js ?>-->
  <!--<?- SSRDataScript ?>-->
</body>
</html>`;

const headChunksTemplate = `<!DOCTYPE html>
<html>
<head>
  <title></title>
  <!--<?- chunksMap.css ?>-->
  <!--<?- chunksMap.js ?>-->
</head>
<body>
  <div id="root"><!--<?- html ?>--></div>
  <!--<?- SSRDataScript ?>-->
</body>
</html>`;

const templates = { defaultTemplate, titleTemplate, headChunksTemplate };

const Content = () => (
  <main>
    <h1 className="title">Hello Modern.js</h1>
    <svg viewBox="0 0 10 10" aria-hidden="true">
      <path d="M0 0L10 10" />
    </svg>
    <ul>
      {['a', 'b', 'c'].map(item => (
        <li key={item}>{`Item ${item}`}</li>
      ))}
    </ul>
  </main>
);

const apps: Record<string, () => React.ReactElement> = {
  withoutHelmet: () => <Content />,
  helmetTitle: () => (
    <>
      <Helmet>
        <title>Page Title</title>
        <meta name="description" content="page description" />
      </Helmet>
      <Content />
    </>
  ),
  helmetAttributes: () => (
    <>
      <Helmet
        htmlAttributes={{ lang: 'en' }}
        bodyAttributes={{ class: 'dark' }}
      >
        <title>Page Title</title>
        <link rel="canonical" href="https://modernjs.dev/" />
        <style>{'body { margin: 0; }'}</style>
        <script>{'window.__helmet = true;'}</script>
      </Helmet>
      <Content />
    </>
  ),
  // the app html contains a <title>, e.g. of an svg icon or a React 19 <title>
  svgTitle: () => (
    <>
      <Content />
      <svg>
        <title>Close</title>
      </svg>
    </>
  ),
  svgTitleWithHelmet: () => (
    <>
      <Helmet>
        <title>Page Title</title>
      </Helmet>
      <Content />
      <svg>
        <title>Close</title>
      </svg>
    </>
  ),
  reactTitle: () => (
    <>
      <title>React Title</title>
      <Content />
    </>
  ),
};

function createRenderOptions(
  htmlTemplate: string,
  htmlModifiers: BuildHtmlCb[] = [],
) {
  const ssrContext = {
    request: {
      params: {},
      query: {},
      pathname: '/',
      host: 'localhost:8080',
      url: 'http://localhost:8080/',
      headers: {},
    },
    reporter: { sessionId: 'session-id' },
    htmlModifiers,
  };
  return {
    resource: {
      htmlTemplate,
      entryName: 'main',
      route: {},
      loadableStats: undefined,
      routeManifest: undefined,
    },
    runtimeContext: { ssrContext },
    config: { ssr: { mode: 'string' } },
    onError: rstest.fn(),
    onTiming: rstest.fn(),
  } as any;
}

function render(htmlTemplate: string, app: React.ReactElement) {
  return renderString(
    new Request('http://localhost:8080/'),
    app,
    createRenderOptions(htmlTemplate),
  );
}

// The order used to build the html before the app html was moved to the end.
async function renderWithPreviousOrder(
  htmlTemplate: string,
  app: React.ReactElement,
) {
  const html = ReactDomServer.renderToString(app, {
    identifierPrefix: SSR_HYDRATION_ID_PREFIX,
  });
  const helmetData = Helmet.renderStatic();
  const { runtimeContext, config } = createRenderOptions(htmlTemplate);
  const chunkSet: ChunkSet = {
    renderLevel: RenderLevel.SERVER_RENDER,
    ssrScripts: '',
    jsChunk,
    cssChunk,
  };
  new SSRDataCollector({
    runtimeContext,
    request: new Request('http://localhost:8080/'),
    ssrConfig: config.ssr,
    ssrContext: runtimeContext.ssrContext,
    chunkSet,
  }).effect();

  return buildHtml(htmlTemplate, [
    template => safeReplace(template, HTML_PLACEHOLDER, html),
    template => safeReplace(template, CHUNK_JS_PLACEHOLDER, chunkSet.jsChunk),
    template => safeReplace(template, CHUNK_CSS_PLACEHOLDER, chunkSet.cssChunk),
    template =>
      safeReplace(template, SSR_DATA_PLACEHOLDER, chunkSet.ssrScripts),
    createReplaceHelemt(helmetData),
  ]);
}

describe('renderString html building', () => {
  const previousContext = getGlobalInternalRuntimeContext();

  afterAll(() => {
    setGlobalInternalRuntimeContext(previousContext);
  });

  beforeAll(() => {
    setGlobalInternalRuntimeContext({
      hooks: {
        extendStringSSRCollectors: {
          call: ({ chunkSet }: { chunkSet: ChunkSet }) => [
            {
              effect() {
                chunkSet.jsChunk += jsChunk;
                chunkSet.cssChunk += cssChunk;
              },
            },
          ],
        },
      },
    } as any);
  });

  const cases = Object.keys(templates).flatMap(template =>
    Object.keys(apps).map(app => [template, app]),
  ) as [keyof typeof templates, keyof typeof apps][];

  it.each(cases)(
    'should build the same html as before for %s and %s',
    async (templateName, appName) => {
      const template = templates[templateName];
      const App = apps[appName];

      const expected = await renderWithPreviousOrder(template, <App />);
      const html = await render(template, <App />);

      expect(html).toBe(expected);
      expect(html).toContain('<h1 class="title">Hello Modern.js</h1>');
      expect(html).toContain(jsChunk);
      expect(html).toContain('window._SSR_DATA');
      expect(html).not.toContain(HTML_PLACEHOLDER);
      expect(html).not.toContain(CHUNK_JS_PLACEHOLDER);
      expect(html).not.toContain(SSR_DATA_PLACEHOLDER);
    },
  );

  it('should not add the helmet title when the app html has a title', async () => {
    const html = await render(defaultTemplate, <apps.reactTitle />);

    expect(html).toContain('<div id="root"><title>React Title</title><main>');
    expect(html).not.toContain('<title data-react-helmet="true">');
  });

  it('should only replace the placeholders of the template', async () => {
    const appHtml = [
      CHUNK_JS_PLACEHOLDER,
      CHUNK_CSS_PLACEHOLDER,
      SSR_DATA_PLACEHOLDER,
    ].join('');
    const html = await render(
      defaultTemplate,
      <div dangerouslySetInnerHTML={{ __html: appHtml }} />,
    );

    expect(html).toContain(`<div id="root"><div>${appHtml}</div></div>`);
    expect(html).toContain(`</div></div>\n  ${jsChunk}\n  <script>`);
  });

  it('should insert the app html last when the template has a title', async () => {
    // The app html has a <title>, but helmet finds the template's one first,
    // so the template edits still run before the app html is inserted.
    const appHtml = `<svg><title>Close</title></svg>${CHUNK_JS_PLACEHOLDER}`;
    const html = await render(
      titleTemplate,
      <div dangerouslySetInnerHTML={{ __html: appHtml }} />,
    );

    expect(html).toContain(`<div id="root"><div>${appHtml}</div></div>`);
    expect(html).toContain(`</div></div>\n  ${jsChunk}\n  <script>`);
  });

  it('should run html modifiers on the complete html', async () => {
    const htmlModifier = rstest.fn(
      (template: string) => `${template}<!-- modified -->`,
    );
    const html = await renderString(
      new Request('http://localhost:8080/'),
      <Content />,
      createRenderOptions(titleTemplate, [htmlModifier]),
    );

    expect(htmlModifier).toHaveBeenCalledTimes(1);
    const [document] = htmlModifier.mock.calls[0];
    expect(document).toContain('<h1 class="title">Hello Modern.js</h1>');
    expect(document).toContain('window._SSR_DATA');
    expect(document).toContain(jsChunk);
    expect(document).toContain(cssChunk);
    expect(html).toBe(`${document}<!-- modified -->`);
  });
});
